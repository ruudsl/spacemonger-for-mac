def escape(value):
    return value.replace("\\", "\\\\").replace('"', '\\"')


def write_lang(code, table):
    folder = os.path.join(BASE, f"{code}.lproj")
    os.makedirs(folder, exist_ok=True)
    lines = [f"/* SpaceMonger — {code} (generated by tools/make_locales.py) */", ""]
    for key in ORDER:
        value = table.get(key, EN[key])
        lines.append(f'"{escape(key)}" = "{escape(value)}";')
    path = os.path.join(folder, "Localizable.strings")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  wrote {code}.lproj ({len(ORDER)} keys)")


def main():
    print("Generating Localizable.strings…")
    write_lang("en", EN)
    for code, table in T.items():
        write_lang(code, table)
    print("Done.")


if __name__ == "__main__":
    main()

